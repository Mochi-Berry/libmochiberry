#!/usr/bin/env sh
#
# transpile-basm.sh — transpile a JavaScript app to a *Berry assembler*
# (.basm) source so it can become a Berry OS binary via beasm.
#
# beasm (beasm/beasm.c, the Berry Assembler for UBerryNix) assembles
# FASM-style .basm sources into native Berry binaries (.befb/.bex/.bdl/...).
# MBJS apps ship as bytecode, so the transpiled .basm embeds the app's
# compiled bytecode as a data blob (db directives) plus a version/name
# record, exported through the standard BERRY_EXPORT table — the Berry OS
# loader/bootloader can then load the blob and hand it to the MBJS runtime
# (mbjs_std_eval_binary), exactly like an OTA app.mbc.
#
# If beasm is available it is used to assemble the .basm to a .bdl; if not,
# the script prints the exact command so the .basm can be assembled inside
# UBerryNix (self-hosted) or after installing beasm.
#
# Usage:
#   sh scripts/transpile-basm.sh <app.js> [out.basm]
#
set -u

cd "$(dirname "$0")/.."

APP="${1:-examples/app_mochiberry.js}"
OUT_BASM="${2:-dist/transpile/app.basm}"
BASE="$(basename "$APP" .js)"

if [ ! -x build/mbjsc ]; then
    echo "building engine first (make)..."
    make -j4 || exit 1
fi

echo "== transpile to Berry assembler (.basm): $APP -> $OUT_BASM =="
mkdir -p "$(dirname "$OUT_BASM")"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

build/mbjsc -b -o "$TMP/app.mbc" "$APP" || exit 1
SIZE="$(wc -c < "$TMP/app.mbc")"

{
    echo "; generated by transpile-basm.sh — MBJS (libmochiberry) bytecode blob"
    echo "; app:     $APP"
    echo "; package: my.berrylabfoundation.mochiberry"
    echo "; bytecode: $SIZE bytes (mbjsc -b output; run via mbjs_std_eval_binary)"
    echo ""
    echo "section '.data' data readable"
    echo ""
    # one 16-byte row per line; the first row carries the label, the rest
    # are bare `db` rows (beasm has no line-continuation and no label reuse)
    od -An -tx1 -v "$TMP/app.mbc" | tr -s ' ' '\n' | grep -v '^$' | awk '
BEGIN { col = 0; row = 0 }
{
    if (col == 0) {
        if (row == 0) printf "mbjs_app_bytecode db "
        else          printf "db "
        row++
    }
    if (col > 0) printf ", "
    printf "0x%s", $0
    col++
    if (col == 16) { print ""; col = 0 }
}
END { if (col > 0) print "" }
'
    echo "mbjs_app_bytecode_len = \$ - mbjs_app_bytecode"
    echo ""
    echo "mbjs_app_name db '$BASE', 0"
    echo "mbjs_app_pkg db 'my.berrylabfoundation.mochiberry', 0"
    echo "mbjs_app_abi db 'mbjs-bytecode-1', 0"
    echo ""
    echo "section '.exports' data readable"
    echo ""
    echo "BERRY_EXPORT mbjs_app_bytecode, 1"
    echo ""
    echo "; Terminator .exports"
    echo "dd 0, 0, 0"
} > "$OUT_BASM"

echo "generated $OUT_BASM ($SIZE bytecode bytes)."

# Assemble with beasm when available (host build or UBerryNix self-host).
BEASM=""
if [ -x build/beasm ]; then
    BEASM="build/beasm"
elif [ -f beasm/beasm.c ]; then
    echo "building beasm (beasm/beasm.c)..."
    cc -O2 -o build/beasm beasm/beasm.c 2>/dev/null && BEASM="build/beasm" || true
fi

if [ -n "$BEASM" ]; then
    OUT_BDL="$(dirname "$OUT_BASM")/$(basename "$OUT_BASM" .basm).bdl"
    echo "assembling with $BEASM ..."
    if "$BEASM" "$OUT_BASM" -o "$OUT_BDL" --format bdl --entry mbjs_app_bytecode 2>&1; then
        echo
        echo "== Berry binary ready =="
        ls -la "$OUT_BDL"
    else
        echo "beasm assembly failed; the .basm source is still valid." >&2
    fi
else
    echo
    echo "beasm not available. Assemble later with:"
    echo "  build/beasm $OUT_BASM -o dist/transpile/$(basename "$OUT_BASM" .basm).bdl --format bdl --entry mbjs_app_bytecode"
fi
echo "done."
