"""Generate test262_prelude.js from the patch layer (reproducible).

Usage: python scripts/gen_prelude.py [outfile]
"""
import io, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PATCHES = ["patch_intl.js", "patch_ecma2025.js", "patch_ecma2026.js",
           "patch_awaitdict.js", "patch_temporal_full.js"]
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "test262_prelude.js")

parts = ["// test262 prelude — generated by scripts/gen_prelude.py (do not edit by hand)\n",
         "globalThis.__mbjs_patches = globalThis.__mbjs_patches || {};\n",
         "globalThis.js_registry = globalThis.__mbjs_patches;\n",
         "globalThis.js_record = function(name, how){ globalThis.__mbjs_patches[name] = how; };\n",
         "globalThis.__mbjs_prelude = {loaded:0, failed:[]};\n"]
for p in PATCHES:
    path = os.path.join(ROOT, "patches", p)
    if not os.path.exists(path):
        print("LEWATI (tidak ada):", p)
        continue
    code = io.open(path, encoding="utf-8").read()
    parts.append("\n/* ===== %s ===== */\n" % p)
    parts.append('try { (function(){\n')
    parts.append(code)
    parts.append('\n})(); globalThis.__mbjs_prelude.loaded++; }\n')
    parts.append('catch(e) { globalThis.__mbjs_prelude.failed.push(%r + ": " + (e && e.message)); }\n' % p)
io.open(OUT, "w", encoding="utf-8", newline="\n").write("".join(parts))
print("prelude ditulis:", OUT, os.path.getsize(OUT), "bytes")
