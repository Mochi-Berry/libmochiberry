#!/usr/bin/env sh
#
# build-berry.sh — MBJS → BeASM → Berry OS native binary.
#
# What this does (the "sertakan MBJS ke BeASM" integration):
#
#   1. mbjsc -b compiles the app to bytecode (the same format OTA uses).
#   2. The bytecode blob is embedded in a .basm module as `db` data.
#   3. The same module declares the MBJS runtime bridge: a table of
#      `dq mbjs_berry_*` references. beasm turns those into .cherryreva
#      relocations, so the Berry OS loader links the app module against the
#      MBJS runtime (platform/berry) at load time.
#   4. An exported entry point (mbjs_app_entry) boots the engine on the
#      arena, runs the embedded bytecode and tears down — all in beasm
#      assembly, i.e. the app runs natively on Berry OS.
#   5. Host verification: the same .basm is converted to GNU as
#      (scripts/basm-to-gas.sh), linked against the real engine
#      (platform/berry/mbjs_berry.c + mbjs-mem.c + libmochiberry.so) and
#      executed — so the exact module Berry OS will load is proven to run.
#
# Usage:
#   sh scripts/build-berry.sh <app.js> [out-base]
#     out-base  default: dist/berry/<app-name>
#   Outputs:
#     <out-base>.basm   the Berry assembler module (readable, editable)
#     <out-base>.bex    Berry OS native binary (BEXI64), entry mbjs_app_entry
#     <out-base>.host   host-verification binary (linked against the engine)
#
set -u

cd "$(dirname "$0")/.."

APP="${1:-examples/app_mochiberry.js}"
OUT="${2:-dist/berry/$(basename "${1:-examples/app_mochiberry.js}" .js)}"

[ -x build/mbjsc ] || { echo "building engine first (make)..." && make -j4 || exit 1; }
if [ ! -x build/beasm ]; then
    echo "building beasm (beasm/beasm.c)..."
    mkdir -p build
    cc -O2 -o build/beasm beasm/beasm.c || { echo "FAIL: beasm build failed" >&2; exit 1; }
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$(dirname "$OUT")"

echo "== MBJS -> BeASM -> Berry OS binary: $APP =="

echo "  [1/4] compiling app to bytecode (mbjsc -b)..."
build/mbjsc -b -o "$TMP/app.mbc" "$APP" || exit 1
SIZE="$(wc -c < "$TMP/app.mbc")"
BASE="$(basename "$APP" .js)"

echo "  [2/4] generating Berry assembler module ($SIZE bytecode bytes)..."
{
    echo "; generated by build-berry.sh — MBJS (libmochiberry) in BeASM"
    echo "; app:     $APP"
    echo "; package: my.berrylabfoundation.mochiberry"
    echo "; bytecode: $SIZE bytes (mbjsc -b; runs via mbjs_berry_eval_binary)"
    echo ""
    echo "section '.data' data readable"
    echo ""
    # one 16-byte row per line; first row carries the label, rest are bare db
    od -An -tx1 -v "$TMP/app.mbc" | tr -s ' ' '\n' | grep -v '^$' | awk '
BEGIN { col = 0; row = 0 }
{
    if (col == 0) {
        if (row == 0) printf "mbjs_app_bytecode db "
        else          printf "db "
        row++
    }
    if (col > 0) printf ", "
    printf "0x%s", $0
    col++
    if (col == 16) { print ""; col = 0 }
}
END { if (col > 0) print "" }
'
    echo "mbjs_app_bytecode_len = \$ - mbjs_app_bytecode"
    echo ""
    echo "; MBJSBerryEngine (platform/berry/mbjs_berry.h) — arena + rt + ctx"
    echo "; + budgets. Reserved generously (16 qwords)."
    echo "align 8"
    echo "mbjs_engine resq 16"
    echo ""
    echo "; MBJS runtime bridge — BERRY_IMPORT declares the runtime entry"
    echo "; points (resolved by the Berry OS loader against the MBJS runtime"
    echo "; compiled into the firmware); beasm emits .cherryreva relocations"
    echo "; for the dq references."
    echo "BERRY_IMPORT mbjs_berry_init, mbjs_berry_eval_binary, mbjs_berry_loop, mbjs_berry_destroy"
    echo "mbjs_runtime dq mbjs_berry_init"
    echo "dq mbjs_berry_eval_binary"
    echo "dq mbjs_berry_loop"
    echo "dq mbjs_berry_destroy"
    echo "dq 0"
    echo ""
    echo "section '.text' code executable"
    echo ""
    echo "; Berry OS entry: the bootloader jumps here (BERRY_EXPORT below)."
    echo "mbjs_app_entry:"
    echo "    push rbp"
    echo "    mov rbp, rsp"
    echo "    sub rsp, 32"
    echo "    lea rdi, [rel mbjs_engine]"
    echo "    mov rsi, 0"
    echo "    mov rdx, 0"
    echo "    call [rel mbjs_runtime]"
    echo "    test rax, rax"
    echo "    jnz .entry_fail"
    echo "    lea rdi, [rel mbjs_engine]"
    echo "    lea rsi, [rel mbjs_app_bytecode]"
    echo "    mov rdx, mbjs_app_bytecode_len"
    echo "    call [rel mbjs_runtime + 8]"
    echo "    test rax, rax"
    echo "    jnz .entry_fail"
    echo "    lea rdi, [rel mbjs_engine]"
    echo "    call [rel mbjs_runtime + 16]"
    echo ".entry_done:"
    echo "    lea rdi, [rel mbjs_engine]"
    echo "    call [rel mbjs_runtime + 24]"
    echo "    xor rax, rax"
    echo "    leave"
    echo "    ret"
    echo ".entry_fail:"
    echo "    mov rax, 1"
    echo "    jmp .entry_done"
    echo ""
    echo "; Host-verification shim: run the module on a normal OS (crt1"
    echo "; initialises libc so stdio works). Berry OS ignores this symbol;"
    echo "; the bootloader uses the BERRY_EXPORT entry above."
    echo "main:"
    echo "    push rbp"
    echo "    mov rbp, rsp"
    echo "    call mbjs_app_entry"
    echo "    leave"
    echo "    ret"
    echo ""
    echo "section '.exports' data readable"
    echo ""
    echo "BERRY_EXPORT mbjs_app_entry, 1"
    echo ""
    echo "; Terminator .exports"
    echo "dd 0, 0, 0"
} > "$OUT.basm"

echo "  [3/4] assembling Berry OS binary with beasm..."
if build/beasm "$OUT.basm" -o "$OUT.bex" --format bex --entry mbjs_app_entry 2>&1; then
    MAGIC="$(od -A n -t c -N 6 "$OUT.bex" 2>/dev/null | tr -d ' \n')"
    echo "  beasm: $OUT.bex written ($(wc -c < "$OUT.bex") bytes, magic $MAGIC)"
else
    echo "FAIL: beasm assembly failed (the .basm module is still valid)" >&2
    exit 1
fi

echo "  [4/4] host verification (same module, linked against the engine)..."
if ! sh scripts/basm-to-gas.sh "$OUT.basm" "$TMP/out.s" >/dev/null 2>&1; then
    echo "SKIP: host verification converter failed (module is still valid for Berry OS)" >&2
    exit 0
fi
if cc -O2 -I. -Idist/include "$TMP/out.s" platform/berry/mbjs_berry.c mbjs-mem.c \
        -Ldist -lmochiberry -Wl,-rpath,"$PWD/dist" -o "$OUT.host" 2>/dev/null; then
    "$OUT.host"
    RC=$?
    if [ $RC -eq 0 ]; then
        echo "  host: $OUT.host ran the Berry module OK (exit 0)"
    else
        echo "  host: $OUT.host exited $RC" >&2
        exit $RC
    fi
else
    echo "SKIP: host link failed (module is still valid for Berry OS)" >&2
fi

echo
echo "== Berry binary ready =="
ls -la "$OUT.basm" "$OUT.bex" 2>/dev/null
[ -x "$OUT.host" ] && ls -la "$OUT.host"
echo
echo "Deploy: put $OUT.bex on the Berry OS device; the loader links it"
echo "against the MBJS runtime (platform/berry) via .cherryreva relocations."
echo "done."
