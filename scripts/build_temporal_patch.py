"""Build patches/patch_temporal_full.js from vendor/temporal-polyfill.global.js.

MochiBerry adaptations (documented, reproducible):
  1. GetFormatterParts() parses Intl.DateTimeFormat.formatToParts() instead of
     splitting the `format` string: the MochiBerry Intl shim does not emit ICU-style
     separators/era tokens, so string splitting produced NaN date parts.
  2. Intl.DurationFormat.prototype.format/formatToParts are installed with
     Object.defineProperty: the shim defines `format` as a getter-only accessor and
     a plain assignment throws in strict mode.

Run: python scripts/build_temporal_patch.py
"""
import io, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
VENDOR = os.path.join(ROOT, "vendor", "temporal-polyfill.global.js")
OUT = os.path.join(ROOT, "patches", "patch_temporal_full.js")

HEADER = """/*
 * patch_temporal_full.js — Temporal (ES2026/ES2027) via upstream polyfill 0.9.0
 *
 * Generated by scripts/build_temporal_patch.py from vendor/temporal-polyfill.global.js.
 * Do not edit by hand; edit the vendor build or the adaptation script.
 *
 * MochiBerry adaptations:
 *   - GetFormatterParts(): parse formatToParts() instead of splitting `format`
 *   - Intl.DurationFormat.prototype.format/formatToParts: defineProperty, not assign
 */
"""

def main():
    txt = io.open(VENDOR, encoding="utf-8").read()
    # buang header provenance vendor untuk patch (biarkan satu header)
    body = txt.split("*/", 1)[1].lstrip("\n") if txt.startswith("/*!") else txt

    # Call identifier yang dipakai bundle (esbuild me-rewrite import es-abstract)
    m = re.search(r"([A-Za-z0-9_$.]+)\(IntlDateTimeFormatPrototypeFormatToParts,", body)
    call = m.group(1) if m else "Call"

    new_body = """
  const formatter = getIntlDateTimeFormatEnUsForTimeZone(timeZone);
  // MochiBerry: parse via formatToParts (shim Intl tidak menjamin separator/era gaya ICU)
  const parts = %s(IntlDateTimeFormatPrototypeFormatToParts, formatter, [epochMilliseconds]);
  let year, month, day, hour, minute, second, era = "AD";
  for (let i = 0; i < parts.length; i++) {
    const part = parts[i];
    switch (part.type) {
      case "year": year = part.value; break;
      case "month": month = part.value; break;
      case "day": day = part.value; break;
      case "hour": hour = part.value; break;
      case "minute": minute = part.value; break;
      case "second": second = part.value; break;
      case "era": era = part.value; break;
    }
  }
  if (year === undefined || month === undefined || day === undefined ||
      hour === undefined || minute === undefined || second === undefined) {
    throw new RangeErrorCtor("Intl.DateTimeFormat did not return complete date-time parts");
  }
  const yearNumber = +year;
  const eraInitial = era[0];
  return {
    year: eraInitial === "b" || eraInitial === "B" ? -yearNumber + 1 : yearNumber,
    month: +month,
    day: +day,
    hour: hour === "24" ? 0 : +hour,
    minute: +minute,
    second: +second
  };""" % call

    pat = re.compile(r"(function GetFormatterParts\(timeZone, epochMilliseconds\) \{)(.*?)(\n  \})", re.S)
    body, n = pat.subn(lambda mm: mm.group(1) + new_body + mm.group(3), body, count=1)
    if n != 1:
        sys.exit("GAGAL: GetFormatterParts tidak ditemukan")

    subs = [
      ("IntlDurationFormatPrototype.format = ModifiedIntlDurationFormatPrototypeFormat;",
       "ObjectDefineProperty(IntlDurationFormatPrototype, 'format', { value: ModifiedIntlDurationFormatPrototypeFormat, writable: true, enumerable: false, configurable: true });"),
      ("IntlDurationFormatPrototype.formatToParts = function formatToParts2(durationLike) {",
       "ObjectDefineProperty(IntlDurationFormatPrototype, 'formatToParts', { value: function formatToParts2(durationLike) {"),
      ("""      return import_Call8.default(IntlDurationFormatPrototypeFormatToParts, this, [record]);
    };
  }""",
       """      return import_Call8.default(IntlDurationFormatPrototypeFormatToParts, this, [record]);
    }, writable: true, enumerable: false, configurable: true });
  }"""),
    ]
    for old, new in subs:
        if old not in body:
            sys.exit("GAGAL: pola adaptasi tak ditemukan: %s" % old[:60])
        body = body.replace(old, new, 1)

    body += "\n;globalThis.__mbjs_temporal_full = true;\n"
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(HEADER + body)
    print("patch_temporal_full.js ditulis: %d bytes" % os.path.getsize(OUT))

if __name__ == "__main__":
    main()
