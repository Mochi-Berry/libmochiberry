#!/usr/bin/env sh
#
# transpile-asm.sh — transpile a JavaScript app to *inline assembly*
# (gas / LLVM integrated assembler), freestanding.
#
# Pipeline:
#   build/mbjsc -b app.js  ->  raw bytecode
#   wrap the bytes as `.byte` directives in a .S file with exported
#   symbols mbjsc_app / mbjsc_app_size — pure data, position independent,
#   assembles with gcc/gas, clang/llvm and plain `as`, no libc needed.
#
# Then either:
#   --check  verify the .S assembles freestanding (-ffreestanding -nostdlib),
#   --build  additionally link it with examples/embed_bytecode.c against
#            libmochiberry into a runnable native binary (AOT).
#
# Usage:
#   sh scripts/transpile-asm.sh <app.js> [out.S] [--check|--build]
#
set -u

cd "$(dirname "$0")/.."

APP="${1:-examples/app_mochiberry.js}"
OUT_S="${2:-dist/transpile/app.S}"
MODE="${3:-build}"

if [ ! -x build/mbjsc ]; then
    echo "building engine first (make)..."
    make -j4 || exit 1
fi
if [ ! -f dist/libmochiberry.so ]; then
    echo "building libmochiberry first (make libmochiberry)..."
    make libmochiberry || exit 1
fi

echo "== transpile to inline assembly (gas/llvm): $APP -> $OUT_S =="
mkdir -p "$(dirname "$OUT_S")"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

build/mbjsc -b -o "$TMP/app.mbc" "$APP" || exit 1
SIZE="$(wc -c < "$TMP/app.mbc")"

{
    echo "# generated by transpile-asm.sh — inline assembly, freestanding"
    echo "# bytecode from: $APP ($SIZE bytes)"
    echo ""
    echo "    .section .rodata"
    echo "    .globl mbjsc_app"
    echo "    .type  mbjsc_app, @object"
    echo "mbjsc_app:"
    # od -An -tx1 -v prints one line of hex tokens; split into one token
    # per line, then pack 16 tokens per ".byte" directive.
    od -An -tx1 -v "$TMP/app.mbc" | tr -s ' ' '\n' | grep -v '^$' | awk '
{
    if (col == 0) printf "    .byte"
    else printf ","
    printf " 0x%s", $0
    col++
    if (col == 16) { print ""; col = 0 }
}
END { if (col > 0) print "" }
'
    echo "    .size  mbjsc_app, .-mbjsc_app"
    echo ""
    echo "    .section .rodata"
    echo "    .globl mbjsc_app_size"
    echo "    .align 4"
    echo "    .type  mbjsc_app_size, @object"
    echo "mbjsc_app_size:"
    echo "    .long $SIZE"
    echo "    .size  mbjsc_app_size, .-mbjsc_app_size"
    echo ""
    echo "    .section .note.GNU-stack,\"\",@progbits"
} > "$OUT_S"

echo "freestanding assembly check (-ffreestanding -nostdlib)..."
cc -c -ffreestanding -nostdlib -o /tmp/transpile-asm-check.o "$OUT_S" || {
    echo "FAIL: $OUT_S does not assemble freestanding"
    exit 1
}
echo "PASS: $OUT_S assembles freestanding (gas/llvm clean)"

if [ "$MODE" = "check" ]; then
    echo "done (check only)."
    exit 0
fi

echo "linking native binary with examples/embed_bytecode.c..."
OUT_BIN="$(dirname "$OUT_S")/$(basename "$OUT_S" .S)-native"
cc -O2 -I. -Idist/include "$OUT_S" examples/embed_bytecode.c mbjs-mem.c \
    -Ldist -lmochiberry -Wl,-rpath,"$PWD/dist" -o "$OUT_BIN" || exit 1
echo
echo "== transpiled assembly binary ready =="
ls -la "$OUT_BIN"
echo "run it with: $OUT_BIN"
echo "done."
